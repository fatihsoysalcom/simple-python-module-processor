import os

# --- This script demonstrates a simple, self-contained processing task ---
# It simulates a lightweight "build step" or data transformation that can be
# easily run from a terminal or a simple text editor, without needing a
# full-fledged IDE's complex build system or project setup.

def process_modules(input_filename="modules.txt", output_filename="processed_modules.txt"):
    """
    Reads module names from an input file, processes them,
    and writes the standardized names to an output file.
    """
    
    # 1. Create a dummy input file for demonstration purposes.
    # In a real scenario, this file would pre-exist or be generated by another simple script.
    dummy_input_content = [
        "  core_utils  ",
        "  data_handler",
        "network_layer ",
        "  auth_service",
        "  logging_module  "
    ]
    with open(input_filename, "w") as f:
        for line in dummy_input_content:
            f.write(line + "\n")
    print(f"Created dummy input file: {input_filename}")

    processed_lines = []
    try:
        with open(input_filename, "r") as infile:
            for line_num, line in enumerate(infile, 1):
                # --- Core processing logic: simple string manipulation ---
                # This represents a task that might be part of a larger system,
                # but is handled here with minimal overhead and standard library features.
                cleaned_line = line.strip() # Remove leading/trailing whitespace
                if cleaned_line: # Only process non-empty lines
                    standardized_module = f"MODULE_{cleaned_line.upper()}_V1.0" # Standardize format
                    processed_lines.append(standardized_module)
                    print(f"  Processed line {line_num}: '{line.strip()}' -> '{standardized_module}'")

        with open(output_filename, "w") as outfile:
            for processed_line in processed_lines:
                outfile.write(processed_line + "\n")
        
        print(f"\nSuccessfully processed modules from '{input_filename}' to '{output_filename}'.")
        print("Content of processed_modules.txt:")
        with open(output_filename, "r") as f:
            print(f.read())

    except FileNotFoundError:
        print(f"Error: Input file '{input_filename}' not found.")
    except Exception as e:
        print(f"An error occurred: {e}")
    finally:
        # Clean up the dummy input file to keep the environment tidy
        if os.path.exists(input_filename):
            os.remove(input_filename)
            print(f"Cleaned up dummy input file: {input_filename}")

if __name__ == "__main__":
    process_modules()
